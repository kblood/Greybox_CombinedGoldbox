interface Block {
  file: string;
  blockId: number;
  raw: Uint8Array;
}

function loadBuckBlocks(): Block[] {
  const blocks: Block[] = [];
  for (const file of FILES) {
    const path = `${BUCK}/${file}`;
    if (!existsSync(path)) continue;
    const bytes = new Uint8Array(readFileSync(path));
    for (const b of readDaxDataBlocks(bytes)) blocks.push({ file, blockId: b.blockId, raw: b.raw });
  }
  return blocks;
}

interface DialectCensus {
  desync: number;
  cleanExit: number;
  ranOffEnd: number;
  desyncSample: string[];
}

function census(blocks: Block[], dialect: EclDialect): DialectCensus {
  let desync = 0;
  let cleanExit = 0;
  let ranOffEnd = 0;
  const desyncSample: string[] = [];
  for (const b of blocks) {
    const disasm = disassembleEclBlock(b.raw, dialect);
    if (disasm.badOpcodeAt !== undefined) {
      desync++;
      desyncSample.push(`${b.file}#${b.blockId}@0x${disasm.badOpcodeAt.toString(16)}`);
    } else if (disasm.instructions[disasm.instructions.length - 1]?.mnemonic === 'EXIT') {
      cleanExit++;
    } else {
      ranOffEnd++;
    }
  }
  return { desync, cleanExit, ranOffEnd, desyncSample };
}

function reachCounts(blocks: Block[], dialect: EclDialect, watch: number[]): Record<number, number> {
  const counts: Record<number, number> = {};
  for (const op of watch) counts[op] = 0;
  for (const b of blocks) {
    const disasm = disassembleEclBlock(b.raw, dialect);
    for (const ins of disasm.instructions) {
      if (watch.includes(ins.opcode)) counts[ins.opcode]++;
    }
  }
  return counts;
}

