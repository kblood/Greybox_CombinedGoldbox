/**
 * `loadGame()`'s music census — round 33 R5 (`docs/glbr-format.md` §6) wired a `GLBR` census for
 * any manifest file named `MUSIC.DAX`, pinning Buck Rogers: Countdown to Doomsday AND Matrix
 * Cubed to the exact same {songs:8, events:1959, channels:31} because their `MUSIC.DAX` files
 * are byte-identical.
 *
 * **Round 34 R4 correction**: that identity was the problem, not a second confirmation. Matrix's
 * own unpacked `START.EXE`/`GAME.OVR` never open `MUSIC.DAX` by name (`tools/matrix_music_strings.py`)
 * and instead name three Miles AIL `.XMI` files. `loadGame.ts` now suppresses the `GLBR` census
 * for a `MUSIC.DAX`-shaped file when its OWN manifest also lists `.XMI` file(s) (`hasXmiSiblings`),
 * and censuses those `.XMI` files instead (`xmiMusicCensus`) into the exact same
 * `{songs,events,channels}` shape — Countdown's manifest has no `.XMI` entries, so its behaviour
 * (below) is completely unchanged; this is a manifest-driven rule, not a hardcoded "matrix" check.
 *
 * Bar C from `docs/engine/PLAN-ROUND-34.md` R4 asks for a TWO-SIDED pin: Matrix as 0 GLBR songs /
 * N XMI songs, Countdown's 8-GLBR pin untouched. This file has three describe blocks:
 *   1. Countdown — unchanged control (still 8/1959/31, still from the real checked-in manifest).
 *   2. Matrix, the REAL checked-in manifest. **Phase B landed the three `BUCKA/B/C.XMI` rows**, so
 *      `hasXmiSiblings` is now true against the shipped manifest: the GLBR census is suppressed
 *      (MUSIC.DAX never wins the "first contributing file" slot) and the XMI census takes over —
 *      21 songs / 5702 events / 95 channels, independently reproduced from `xmi.ts` directly in
 *      `matrixXmi.test.ts` and a third time, through a byte-for-byte reproduction of
 *      `xmiMusicCensus` itself, when the Phase B patch was written.
 *   3. Matrix, a TEST-LOCAL manifest clone with the `.XMI` rows STRIPPED BACK OUT — the mutation
 *      control, and the direction of the clone is now inverted relative to how this file read
 *      before Phase B. It proves `hasXmiSiblings` is what drives the switch: with no `.XMI`
 *      sibling in the manifest, the very same `MUSIC.DAX` bytes census as 8/1959/31 again.
 *
 * Blocks 2 and 3 are each other's null. Neither is generated by the code under test: 21/5702/95
 * comes from `xmi.ts` read directly, and 8/1959/31 is the number Countdown's own byte-identical
 * file produces in block 1.
 *
 * Sources are external/never-vendored (Buck: the user's `D:/` DOS install; Matrix: the
 * repo-relative, git-ignored `matrixcubed_extracted/`) — absent source => SKIP, the same
 * convention as every other golden suite in this package.
 */
import { describe, it, expect } from 'vitest';
import { readFile } from 'node:fs/promises';
import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadGame, type GameManifest, type FetchBytes } from '../src/index.js';

const here = fileURLToPath(new URL('.', import.meta.url));
const engineRoot = resolve(here, '..');
const repoRoot = resolve(engineRoot, '..', '..');

const fsFetch: FetchBytes = async (path: string): Promise<Uint8Array> => {
  const abs = resolve(repoRoot, path); // path.resolve leaves an already-absolute `path` (e.g. D:/...) unchanged
  return new Uint8Array(await readFile(abs));
};

/**
 * ROUND 35 R6 -- WHY THE GUARDS BELOW ARE `it.skip`, NOT `if (...) return`.
 *
 * Until 2026-09-05 each `it` in this file opened with
 * `if (!musicFile || !existsSync(...)) { console.warn('skip: ...'); return; }`.
 * A bare `return` inside an `it` is a PASS, not a skip. Measured, not argued: with
 * `matrixcubed_extracted/BuckRogers2/c/Matrix/MUSIC.DAX` renamed away, `vitest run
 * test/loadGameGlbrMusic.test.ts` printed `Tests 3 passed (3)` -- both Matrix blocks, which
 * are round 34 R4's entire XMI correction (21/5702/95) AND its own mutation control, went
 * green having asserted nothing. On any fresh clone (`matrixcubed_extracted/` is git-ignored)
 * that is what this file reported. The sibling `matrixXmi.test.ts` already used `it.skip` and
 * correctly printed `2 skipped` under the same rename -- so this was one file's defect, not a
 * harness property.
 *
 * Two changes: (1) fixture presence is resolved ONCE at module load and gates each `describe`
 * with `it.skip`, so an absent source is visible in the runner output instead of silently
 * green; (2) the manifest-shape contract -- that the checked-in Matrix manifest lists exactly
 * BUCKA/BUCKB/BUCKC.XMI, which is what makes `hasXmiSiblings` true -- moved into its own `it`
 * that needs NO external source, so round 34's correction is falsifiable on a fresh clone.
 * Every `it` that does need bytes re-asserts fixture presence with an `expect` as its first
 * statement, so a source that disappears mid-run fails rather than passing.
 */
function manifestSync(manifestFile: string): GameManifest | null {
  const manifestPath = resolve(repoRoot, 'apps', 'web', 'games', manifestFile);
  if (!existsSync(manifestPath)) return null;
  return JSON.parse(readFileSync(manifestPath, 'utf8')) as GameManifest;
}

const musicDaxPath = (m: GameManifest | null): string | null =>
  m?.files.find((f) => /music\.dax$/i.test(f.path))?.path ?? null;
const xmiPaths = (m: GameManifest | null): string[] =>
  (m?.files ?? []).filter((f) => /\.xmi$/i.test(f.path)).map((f) => f.path);
const present = (rel: string | null): boolean => !!rel && existsSync(resolve(repoRoot, rel));

const countdownManifest = manifestSync('buck-rogers-countdown-to-doomsday.json');
const countdownMusic = musicDaxPath(countdownManifest);
const haveCountdown = !!countdownManifest && present(countdownMusic);

const matrixManifest = manifestSync('buck-rogers-matrix-cubed.json');
const matrixMusic = musicDaxPath(matrixManifest);
const matrixXmi = xmiPaths(matrixManifest);
const haveMatrix =
  !!matrixManifest && present(matrixMusic) && matrixXmi.length > 0 && matrixXmi.every(present);

describe('loadGame — GLBR music census, Countdown to Doomsday (unchanged control)', () => {
  if (!haveCountdown) {
    it.skip('source missing (Buck Rogers DOS install / its MUSIC.DAX at the manifest path)', () => {});
    return;
  }

  it('buck-rogers-countdown-to-doomsday: game.music reports {songs:8, events:1959, channels:31}', async () => {
    // Fixture presence asserted BEFORE anything can return: a `describe`-level skip decides
    // whether this body runs at all, and this line makes a mid-run disappearance a failure.
    expect(countdownManifest).not.toBeNull();
    expect(countdownMusic).not.toBeNull();
    expect(existsSync(resolve(repoRoot, countdownMusic as string))).toBe(true);
    const manifest = countdownManifest as GameManifest;
    const musicFile = manifest.files.find((f) => f.path === countdownMusic)!;

    const game = await loadGame(manifest, fsFetch);

    expect(game.id).toBe('buck-rogers-countdown-to-doomsday');
    expect(game.music).toBeDefined();
    expect(game.music?.file).toBe(musicFile.path);
    expect(game.music?.format).toBe('glbr'); // round 34: the census carries which format produced it
    expect(game.music?.songs).toBe(8);
    expect(game.music?.events).toBe(1959);
    expect(game.music?.channels).toBe(31);

    // The manifest entry itself stays a decode:false data file (unaffected by the census probe).
    const musicResult = game.categories.flatMap((c) => c.files).find((f) => f.path === musicFile.path);
    expect(musicResult?.skipped).toBeTruthy();
    expect(musicResult?.frames.length ?? 0).toBe(0);
  });
});

describe('Matrix Cubed manifest shape — no external source needed (round 35 R6)', () => {
  // Deliberately OUTSIDE the fixture guard. `hasXmiSiblings` is a property of the CHECKED-IN
  // manifest, so round 34 R4's correction ("Matrix's manifest did not yet list the .XMI files"
  // -> Phase B listed them) is checkable on a bare clone. Before this round the same assertion
  // sat behind a `matrixcubed_extracted/` guard and could not fail there.
  it('the checked-in manifest lists exactly BUCKA/BUCKB/BUCKC.XMI', () => {
    expect(matrixManifest).not.toBeNull();
    expect(musicDaxPath(matrixManifest)).not.toBeNull();
    expect(xmiPaths(matrixManifest).map((p) => p.split('/').pop()).sort()).toEqual([
      'BUCKA.XMI',
      'BUCKB.XMI',
      'BUCKC.XMI',
    ]);
  });
});

describe('loadGame — Matrix Cubed, the REAL checked-in manifest (post-Phase-B: .XMI rows present)', () => {
  if (!haveMatrix) {
    it.skip('source missing (matrixcubed_extracted/, git-ignored)', () => {});
    return;
  }

  it('reports the XMI census (21 songs / 5702 events / 95 channels) and suppresses the byte-identical MUSIC.DAX entirely', async () => {
    expect(existsSync(resolve(repoRoot, matrixMusic as string))).toBe(true);
    expect(matrixXmi.length).toBe(3);
    expect(matrixXmi.every(present)).toBe(true);
    const manifest = matrixManifest as GameManifest;
    const musicFile = manifest.files.find((f) => f.path === matrixMusic)!;

    const game = await loadGame(manifest, fsFetch);

    expect(game.id).toBe('buck-rogers-matrix-cubed');
    expect(game.music).toBeDefined();
    expect(game.music?.format).toBe('xmi');
    // The GLBR file contributes nothing: it is not the summary's named file, and the numbers are
    // not the ones it would have produced.
    expect(game.music?.file).not.toBe(musicFile.path);
    expect(matrixXmi).toContain(game.music?.file);
    expect(game.music?.songs).toBe(21);
    expect(game.music?.events).toBe(5702);
    expect(game.music?.channels).toBe(95);
    expect(game.music?.songs).not.toBe(8);

    // The MUSIC.DAX manifest entry itself is untouched by any of this — still a skipped data file.
    const musicResult = game.categories.flatMap((c) => c.files).find((f) => f.path === musicFile.path);
    expect(musicResult?.skipped).toBeTruthy();
    expect(musicResult?.frames.length ?? 0).toBe(0);
  });
});

describe('loadGame — Matrix Cubed, test-local manifest with the .XMI rows STRIPPED (mutation control)', () => {
  if (!haveMatrix) {
    it.skip('source missing (matrixcubed_extracted/, git-ignored)', () => {});
    return;
  }

  it('mutation: removing the .XMI entries reverts the very same MUSIC.DAX bytes to the OLD 8/1959/31 GLBR numbers (proves hasXmiSiblings, not some other property, drives the switch)', async () => {
    expect(existsSync(resolve(repoRoot, matrixMusic as string))).toBe(true);
    const baseManifest = matrixManifest as GameManifest;
    const musicFile = baseManifest.files.find((f) => f.path === matrixMusic)!;

    const stripped: GameManifest = {
      ...baseManifest,
      files: baseManifest.files.filter((f) => !/\.xmi$/i.test(f.path)),
    };
    // Guard the mutation itself: if the Phase B rows were ever removed from the real manifest this
    // clone would be identical to it, and the test would silently stop being a mutation at all.
    expect(stripped.files.length).toBeLessThan(baseManifest.files.length);

    const game = await loadGame(stripped, fsFetch);

    expect(game.music?.format).toBe('glbr');
    expect(game.music?.file).toBe(musicFile.path);
    expect(game.music?.songs).toBe(8);
    expect(game.music?.events).toBe(1959);
    expect(game.music?.channels).toBe(31);
  });
});
