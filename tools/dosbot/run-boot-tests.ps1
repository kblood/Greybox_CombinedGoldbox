# dosbot/run-boot-tests.ps1 — the unattended boot-verification suite.
# Runs the boot-watcher on each build dir and writes a single consolidated markdown
# report (results.md) + copies the key proof frame for each. Designed to run while the
# user is away: it answers "does each rebuilt DQK executable boot to the right title?"
#
# Usage: pwsh tools/dosbot/run-boot-tests.ps1
. "C:\Modding\GoldBox\tools\dosbot\lib.ps1"

$tests = @(
  @{ label="A-retitle"; dir="C:\Modding\GoldBox\build\dqk-retitle"; expect="CHAMPIONS OF KRYNN"; what="Retitle-only build (isolates the 23-byte DQK.EXE title patch)" },
  @{ label="B-content"; dir="C:\Modding\GoldBox\build\cok-on-dqk";  expect="CHAMPIONS OF KRYNN"; what="Full content conversion (ported GEO/MON/ECL GLBs + retitle)" }
)

$root = "C:\Modding\GoldBox\tools\dosbot\runs"
$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$suiteDir = Join-Path $root "suite-$stamp"
New-Item -ItemType Directory -Force $suiteDir | Out-Null
$rows = @()

foreach ($t in $tests) {
  if (-not (Test-Path $t.dir)) { Write-Host "[suite] SKIP $($t.label): $($t.dir) missing"; continue }
  Write-Host "===== $($t.label) : $($t.dir) ====="
  $proc = Start-Dosbox -MountDir $t.dir
  $hwnd = Wait-DosboxWindow -Proc $proc -TimeoutSec 20
  if ($hwnd -eq [IntPtr]::Zero) { Write-Host "[suite] no window"; Stop-Dosbox $proc; continue }
  Start-Sleep -Seconds 8   # boot through MicroMagic splash to the front menu

  # Poll frequently: the patched title lives on the front PLAY/DEMO/QUIT menu, which shows
  # BEFORE the idle timer auto-launches the (unpatched, art-baked) intro. Break on match.
  $reached=$false; $title=$null; $crashed=$false; $best=$null
  for ($i=1; $i -le 12; $i++) {
    $png = Join-Path $suiteDir ("$($t.label)_f{0:00}.png" -f $i)
    Capture-DosboxWindow -Hwnd $hwnd -OutPng $png | Out-Null
    $v = Invoke-Vision -Png $png
    $hit = ("$($v.game_title)" -match [regex]::Escape($t.expect)) -or ("$($v.visible_text)" -match [regex]::Escape($t.expect))
    Write-Host ("  [{0,2}] {1,-11} hit={2,-5} title={3}" -f $i, $v.screen, $hit, "$($v.game_title)")
    if ($v.looks_crashed) { $crashed=$true }
    if ($hit) { $reached=$true; $title=$v.game_title; $best=$png; break }
    Start-Sleep -Milliseconds 1500
  }
  Stop-Dosbox -Proc $proc
  if (-not $best) { $best = Join-Path $suiteDir ("$($t.label)_f1.png") }
  $proofName = "$($t.label)_PROOF.png"
  Copy-Item $best (Join-Path $suiteDir $proofName) -Force
  $rows += [pscustomobject]@{ label=$t.label; what=$t.what; expect=$t.expect; reached=$reached; title=$title; crashed=$crashed; proof=$proofName }
  Write-Host "  -> reached=$reached crashed=$crashed`n"
}

# write markdown report
$md = @()
$md += "# DOSBox boot-test results"
$md += ""
$md += "Generated by ``tools/dosbot/run-boot-tests.ps1`` — unattended, vision-judged (qwen3.5:4b on the RTX 5090)."
$md += ""
$md += "| Test | Expected title on screen | Reached? | Crashed? | Proof |"
$md += "|------|--------------------------|----------|----------|-------|"
foreach ($r in $rows) {
  $ok = if ($r.reached -and -not $r.crashed) { "✅ PASS" } else { "❌ FAIL" }
  $md += "| **$($r.label)** — $($r.what) | $($r.expect) | $($r.reached) | $($r.crashed) | $ok ![$($r.label)]($($r.proof)) |"
}
$md += ""
$md += "Input note: DOSBox/SDL on this build accepts **mouse** input (clicks reach the game) but ignores synthetic **keyboard** scancodes; menu navigation in deeper tests uses clicks (and is a natural fit for the UI-TARS click-coordinate model)."
$md -join "`n" | Set-Content (Join-Path $suiteDir "results.md") -Encoding UTF8

Write-Host "===== SUITE COMPLETE ====="
$rows | Format-Table label, reached, crashed, title -AutoSize
Write-Host "report: $(Join-Path $suiteDir 'results.md')"
