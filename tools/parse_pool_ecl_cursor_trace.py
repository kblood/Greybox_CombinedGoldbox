#!/usr/bin/env python3
"""Normalize Pool's bounded runtime ECL-cursor probe into durable negative evidence."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


EXPECTED_SAVE_SHA256 = "2bc5a41f17c3dcc69555866e459a6db8da839fd22bb559aecd2797dba595a1a4"
EXPECTED_PARSER = "30CF:0000"
EXPECTED_DGROUP_OFFSET = 0x49ED
POOL_ADDRESS_ADDEND = 0x6700
SEARCH_LOCATION = 0x9AB7
COMBAT = 0xB1A0


def virtual_address(raw_member_offset: int) -> int:
    return (raw_member_offset - 2 - POOL_ADDRESS_ADDEND) & 0xFFFF


def normalize(raw_path: Path) -> dict[str, Any]:
    source = json.loads(raw_path.read_text(encoding="utf-8-sig"))
    errors: list[str] = []
    if source.get("save_sha256") != EXPECTED_SAVE_SHA256:
        errors.append("route save hash mismatch")
    records = list(source.get("ecl_cursor_records", []))
    if not records:
        errors.append("cursor trace has no records")
    for record in records:
        expected = virtual_address(int(record["raw_member_offset"]))
        if int(record["virtual_address"]) != expected:
            errors.append(f"cursor {record['index']} raw-to-virtual mismatch")
        if record["parser_cs_ip"] != EXPECTED_PARSER:
            errors.append(f"cursor {record['index']} parser identity mismatch")
        if int(record["dgroup_offset"]) != EXPECTED_DGROUP_OFFSET:
            errors.append(f"cursor {record['index']} DGROUP offset mismatch")

    addresses = [int(record["virtual_address"]) for record in records]
    reached_search = any(SEARCH_LOCATION <= address < COMBAT for address in addresses)
    if bool(source.get("reached_search_location_range")) != reached_search:
        errors.append("source search-location verdict disagrees with normalized cursor range")

    return {
        "schema_version": 1,
        "captured_at": "2026-07-15",
        "profile_id": "pool-of-radiance",
        "source_trace": raw_path.name,
        "save_sha256": source.get("save_sha256"),
        "parser": {
            "runtime_cs_ip": EXPECTED_PARSER,
            "game_ovr_file_offset": 0x74D3,
            "retail_prefix_hex": "5589e583ec08",
            "dgroup_cursor_offset": EXPECTED_DGROUP_OFFSET,
            "address_addend": POOL_ADDRESS_ADDEND,
        },
        "route": source.get("route"),
        "cursor_count": len(records),
        "cursor_min": min(addresses) if addresses else None,
        "cursor_max": max(addresses) if addresses else None,
        "cursor_sequence": addresses,
        "records": records,
        "targets": {
            "search_location": SEARCH_LOCATION,
            "combat": COMBAT,
            "reached_search_location_range": reached_search,
            "reached_combat": COMBAT in addresses,
        },
        "validation": {"ok": not errors, "errors": errors},
        "verdict": "reentry_did_not_dispatch_selected_search_location",
        "claim_boundary": (
            "proves the captured re-entry parser sequence did not reach ECL1#18 SearchLocation; "
            "it does not prove that the ECL route is unreachable under corrected host state"
        ),
    }


def render_markdown(payload: dict[str, Any]) -> str:
    sequence = " ".join(f"{value:04X}" for value in payload["cursor_sequence"])
    return "\n".join([
        "# Pool ECL cursor re-entry probe",
        "",
        "> Generated by `tools/parse_pool_ecl_cursor_trace.py` from a process-scoped DOSBox-X trace.",
        "",
        f"- Validation: **{'PASS' if payload['validation']['ok'] else 'FAIL'}**",
        f"- Parser: `{payload['parser']['runtime_cs_ip']}` / `GAME.OVR:0x{payload['parser']['game_ovr_file_offset']:X}`",
        f"- DGROUP cursor: `0x{payload['parser']['dgroup_cursor_offset']:X}`",
        f"- Cursor records: `{payload['cursor_count']}`",
        f"- SearchLocation `0x{SEARCH_LOCATION:X}` reached: **{payload['targets']['reached_search_location_range']}**",
        f"- COMBAT `0x{COMBAT:X}` reached: **{payload['targets']['reached_combat']}**",
        "",
        "## Virtual-address sequence",
        "",
        f"`{sequence}`",
        "",
        "## Verdict",
        "",
        "The byte-validated operand parser ran, but this bounded leave/re-entry stayed below the",
        "selected `search_location` entry. The earlier surprise-goblin/orc trace is therefore not",
        "execution evidence for ECL `COMBAT 0xB1A0`.",
        "",
        "## Claim boundary",
        "",
        payload["claim_boundary"],
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--trace", type=Path, required=True)
    parser.add_argument("--fixture", type=Path, required=True)
    parser.add_argument("--markdown", type=Path, required=True)
    parser.add_argument("--strict", action="store_true")
    args = parser.parse_args()
    payload = normalize(args.trace)
    args.fixture.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8", newline="\n")
    args.markdown.write_text(render_markdown(payload), encoding="utf-8", newline="\n")
    print(
        f"[pool-ecl-cursor] records={payload['cursor_count']} "
        f"search={payload['targets']['reached_search_location_range']} "
        f"ok={payload['validation']['ok']}"
    )
    return 1 if args.strict and not payload["validation"]["ok"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
