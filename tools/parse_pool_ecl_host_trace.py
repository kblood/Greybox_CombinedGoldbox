#!/usr/bin/env python3
"""Normalize Pool's runtime ECL host selector trace against retail DAX inventories."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import goldbox_corpus


EXPECTED_SAVE_SHA256 = "2bc5a41f17c3dcc69555866e459a6db8da839fd22bb559aecd2797dba595a1a4"
EXPECTED_PARSER = "30CF:0000"
EXPECTED_DGROUP = "14A0"
EXPECTED_HEADER_OFFSET = 0x49E3
EXPECTED_MEMBER_FIELD = 0x1E4
EXPECTED_ARCHIVE_SET_OFFSET = 0x5376
EXPECTED_REQUESTED_MEMBER = 18
EXPECTED_ARCHIVE_SET = 2
TARGET_ARCHIVE_SET = 1
TARGET_SEARCH = 0x9AB7
ENTRY_NAMES = ("vm_run_1", "search_location", "pre_camp_check", "camp_interrupted", "initial_entry")


def dax_headers(pool_dir: Path) -> dict[tuple[int, int], list[int]]:
    result: dict[tuple[int, int], list[int]] = {}
    for path in sorted(pool_dir.glob("ECL*.DAX")):
        suffix = int(path.stem[3:])
        for block in goldbox_corpus.read_dax_blocks(path):
            raw = block["raw"]
            if len(raw) < 22 or raw[:2] != b"\x88\x13":
                continue
            result[(suffix, block["block_id"])] = [
                int.from_bytes(raw[4 + index * 4 : 6 + index * 4], "little")
                for index in range(5)
            ]
    return result


def build_report(trace_path: Path, pool_dir: Path) -> dict[str, Any]:
    trace = json.loads(trace_path.read_text(encoding="utf-8-sig"))
    if trace["save_sha256"] != EXPECTED_SAVE_SHA256:
        raise ValueError("unexpected Pool route save hash")
    initial = trace["initial_host_state"]
    after = trace["after_entry_host_state"]
    if initial != after:
        raise ValueError("host selector state changed during direct entry")
    entries = [initial["header_entries"][name] for name in ENTRY_NAMES]
    inventory = dax_headers(pool_dir)
    matches = [key for key, value in inventory.items() if value == entries]
    if matches != [(2, 20)]:
        raise ValueError(f"live header did not uniquely identify ECL2.DAX#20: {matches}")
    requested = (initial["archive_set"], initial["area_ecl_member_id"])
    records = trace["ecl_cursor_records"]
    if len(records) != 1 or records[0]["parser_cs_ip"] != EXPECTED_PARSER:
        raise ValueError("expected one bounded direct-entry parser record")
    return {
        "schema_version": 1,
        "title": "Pool of Radiance",
        "save_sha256": trace["save_sha256"],
        "runtime": {
            "dgroup_segment": initial["dgroup_segment"],
            "header_table_offset": initial["header_table_offset"],
            "header_entries": initial["header_entries"],
            "member_field_offset": initial["area_ecl_member_field_offset"],
            "requested_member": initial["area_ecl_member_id"],
            "archive_set_offset": initial["archive_set_dgroup_offset"],
            "archive_set": initial["archive_set"],
            "first_parser_cs_ip": records[0]["parser_cs_ip"],
            "first_parser_virtual_address": records[0]["virtual_address"],
        },
        "retail_match": {
            "loaded_header_archive_set": matches[0][0],
            "loaded_header_member": matches[0][1],
            "requested_pair_exists": requested in inventory,
            "target_pair_exists": (TARGET_ARCHIVE_SET, EXPECTED_REQUESTED_MEMBER) in inventory,
            "target_search_location": TARGET_SEARCH,
        },
        "verdict": "game_area_2_member_18_lookup_retains_stale_ecl2_member_20",
        "claim_boundary": (
            "The runtime selector, exact five-word header, retail DAX inventory, and first parser cursor "
            "prove that the staged save does not dispatch ECL1.DAX#18. They do not yet prove how to "
            "construct a coherent game-area-1 save or reach COMBAT 0xB1A0."
        ),
    }


def render_markdown(report: dict[str, Any]) -> str:
    runtime = report["runtime"]
    retail = report["retail_match"]
    header = ", ".join(f"`{name}=0x{value:04X}`" for name, value in runtime["header_entries"].items())
    return "\n".join(
        [
            "# Pool Runtime ECL Host Selector",
            "",
            "> Generated by `tools/parse_pool_ecl_host_trace.py`. Do not edit by hand.",
            "",
            f"- Save SHA-256: `{report['save_sha256']}`.",
            f"- Runtime request: archive/game area `{runtime['archive_set']}`, member `{runtime['requested_member']}`.",
            f"- Header at DGROUP `0x{runtime['header_table_offset']:04X}`: {header}.",
            f"- Exact retail header match: `ECL{retail['loaded_header_archive_set']}.DAX#{retail['loaded_header_member']}`.",
            f"- Requested pair exists: `{str(retail['requested_pair_exists']).lower()}`; target `ECL1.DAX#18` exists: `{str(retail['target_pair_exists']).lower()}`.",
            f"- First direct-entry parser cursor: `{runtime['first_parser_cs_ip']}` at `0x{runtime['first_parser_virtual_address']:04X}`.",
            "",
            "## Verdict",
            "",
            "The staged save requests member 18 while game area 2 is active. `ECL2.DAX` has no member 18,",
            "so the previous ECL2 member-20 buffer remains active. This is why the trace never enters the",
            "selected `ECL1.DAX#18 search_location` routine at `0x9AB7`.",
            "",
            "## Claim Boundary",
            "",
            report["claim_boundary"],
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--trace", type=Path, required=True)
    parser.add_argument("--pool-dir", type=Path, required=True)
    parser.add_argument("--fixture", type=Path, required=True)
    parser.add_argument("--markdown", type=Path, required=True)
    parser.add_argument("--strict", action="store_true")
    args = parser.parse_args()
    report = build_report(args.trace, args.pool_dir)
    if args.strict:
        runtime = report["runtime"]
        retail = report["retail_match"]
        if (
            runtime["dgroup_segment"] != EXPECTED_DGROUP
            or runtime["header_table_offset"] != EXPECTED_HEADER_OFFSET
            or runtime["member_field_offset"] != EXPECTED_MEMBER_FIELD
            or runtime["archive_set_offset"] != EXPECTED_ARCHIVE_SET_OFFSET
            or runtime["requested_member"] != EXPECTED_REQUESTED_MEMBER
            or runtime["archive_set"] != EXPECTED_ARCHIVE_SET
            or retail["requested_pair_exists"]
            or not retail["target_pair_exists"]
        ):
            raise SystemExit("strict failure: Pool ECL host-selector evidence changed")
    args.fixture.parent.mkdir(parents=True, exist_ok=True)
    args.markdown.parent.mkdir(parents=True, exist_ok=True)
    args.fixture.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8", newline="\n")
    args.markdown.write_text(render_markdown(report), encoding="utf-8", newline="\n")
    print(f"pool ECL host selector: {report['verdict']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
