"""Gates the checked-in generated artifact ``apps/web/src/generated/support-evidence.json``.

That file is *generated* by ``tools/goldbox_corpus.py`` but *checked in*, and the shipped
support page imports it directly -- so it is what tells a visitor which games the engine
supports and on what evidence. Until this test existed, no gate regenerated it and diffed
it, so the artifact could certify a claim the code no longer produces and nothing would go
red.

It had already drifted on HEAD when this test was written (2026-08-17): regenerating
rewrote 14 lines, only one of which came from a concurrent ledger edit. The other 13 were
pre-existing drift -- five ``"structurally_absent": []`` keys that HEAD's own code emits,
Gateway's "EXTENDED 2026-08-09" graphics detail, Gateway's replaced ``map_container`` gaps,
and Treasures' measured Amiga-walldef rejection. Every one of those is a claim the support
page was displaying in a stale form.

This is the same defect class as the doc-claim drift pinned by ``test_docs_claims.py``: an
artifact that certifies a claim, with nothing checking it is current.

The regeneration here writes **only into a temp directory** -- all three of the generator's
outputs (``--json``, ``--markdown``, ``--support-json``) are redirected, so running this
test never mutates the working tree. It compares bytes, not parsed JSON: the checked-in
file is a build product, and key order / indentation / trailing newline are part of what
``pnpm build:app`` bundles.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
GENERATOR = REPO_ROOT / "tools" / "goldbox_corpus.py"
ARTIFACT = REPO_ROOT / "apps/web/src/generated/support-evidence.json"

# The generator scans the GOG Galaxy DOS installs, which are an external, never-vendored
# source (CLAUDE.md, "GOG Galaxy DOS installs"). Without them the corpus detects fewer
# games and would legitimately regenerate to different bytes, so this follows the repo's
# standing convention for external sources and skips rather than reporting a false defect.
# This is a precondition on the *inputs*, not a relaxation of the comparison: where the
# sources are present the byte comparison is exact and unconditional.
GOG_ROOT = Path("C:/Program Files (x86)/GOG Galaxy/Games")

REGENERATE_HINT = (
    "Regenerate it and commit the result:\n"
    "    python tools/goldbox_corpus.py --strict\n"
    "Do not hand-edit the file and do not loosen this comparison: it is generated output, "
    "and a difference means the checked-in copy no longer says what the code produces."
)


@pytest.fixture(scope="module")
def run(tmp_path_factory: pytest.TempPathFactory) -> dict[str, bytes]:
    """Run the real generator with every output redirected into a temp directory.

    Returns the regenerated bytes plus the repo artifact's bytes read immediately before
    and after the run, so the inertness of the run is itself testable.
    """
    if not GOG_ROOT.exists():
        pytest.skip(
            f"external GOG Galaxy corpus source not present at {GOG_ROOT}; the "
            "regenerated artifact would not be comparable"
        )
    assert ARTIFACT.exists(), (
        f"{ARTIFACT.relative_to(REPO_ROOT)} is missing entirely. " + REGENERATE_HINT
    )
    before = ARTIFACT.read_bytes()
    out = tmp_path_factory.mktemp("support-evidence")
    proc = subprocess.run(
        [
            sys.executable,
            str(GENERATOR),
            "--json",
            str(out / "goldbox-corpus.json"),
            "--markdown",
            str(out / "goldbox-corpus.md"),
            "--support-json",
            str(out / "support-evidence.json"),
            "--strict",
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=900,
    )
    assert proc.returncode == 0, (
        "`python tools/goldbox_corpus.py --strict` failed, so the checked-in artifact "
        f"cannot be verified (rc={proc.returncode}).\n"
        f"stdout:\n{proc.stdout[-4000:]}\nstderr:\n{proc.stderr[-4000:]}"
    )
    produced = out / "support-evidence.json"
    assert produced.exists(), (
        "the generator reported success but wrote no --support-json output; the "
        f"regeneration is not being exercised.\nstdout:\n{proc.stdout[-4000:]}"
    )
    return {
        "regenerated": produced.read_bytes(),
        "before": before,
        "after": ARTIFACT.read_bytes(),
    }


def test_regeneration_does_not_touch_the_repo_copy(run: dict[str, bytes]) -> None:
    """The regeneration must be inert: this test may never rewrite the repo file.

    Pinned deliberately. If someone later drops the ``--support-json`` redirection, the
    generator's default output path *is* the checked-in artifact -- the comparison below
    would then still pass while silently overwriting the very file it claims to check,
    turning this gate into a no-op that can never go red.
    """
    assert run["after"] == run["before"], (
        "running tools/goldbox_corpus.py from this test rewrote the checked-in artifact. "
        "Every generator output must be redirected into the temp directory; verifying a "
        "file by overwriting it proves nothing."
    )


def test_support_evidence_artifact_is_current(run: dict[str, bytes]) -> None:
    """The checked-in artifact must byte-match a fresh run of its generator."""
    checked_in = run["before"]
    regenerated = run["regenerated"]
    if checked_in == regenerated:
        return

    expected = regenerated.decode("utf-8").splitlines()
    actual = checked_in.decode("utf-8").splitlines()
    import difflib

    diff = list(
        difflib.unified_diff(
            actual,
            expected,
            fromfile="checked-in apps/web/src/generated/support-evidence.json",
            tofile="freshly generated",
            lineterm="",
            n=2,
        )
    )
    changed = sum(1 for line in diff if line[:1] in "+-" and line[:3] not in ("+++", "---"))
    pytest.fail(
        "apps/web/src/generated/support-evidence.json is stale: it is a checked-in "
        f"generated artifact and regenerating it changes {changed} line(s). The shipped "
        "support page imports this file, so the site is certifying claims the code no "
        "longer produces.\n"
        + REGENERATE_HINT
        + "\n\n"
        + "\n".join(diff[:200])
    )
