function Invoke-DebuggerInput {
  param(
    [int]$ProcessId,
    [string]$HelperDll,
    [string]$StatusPath,
    [string]$SnapshotPath,
    [string]$Command,
    [string]$Key,
    [switch]$SnapshotOnly
  )
  $args = @($HelperDll, '--pid', $ProcessId)
  if ($SnapshotOnly) {
    $args += '--snapshot-only'
  } elseif ($Key) {
    $args += @('--key', $Key)
  } else {
    $args += @('--command', $Command)
  }
  $args += @('--status', $StatusPath)
  if ($SnapshotPath) { $args += @('--snapshot', $SnapshotPath) }
  & dotnet @args | Out-Null
  if ($LASTEXITCODE -ne 0) { throw "debugger helper failed with exit $LASTEXITCODE" }
  $status = Get-Content -LiteralPath $StatusPath -Raw | ConvertFrom-Json
  if (-not $status.Success) { throw "debugger helper failed: $($status.Error)" }
  if ($SnapshotPath) { return Get-Content -LiteralPath $SnapshotPath -Raw }
  return ''
}

function Invoke-CombatCallerProbe {
  param(
    [int]$ProcessId,
    [string]$HelperDll,
    [string]$OutDir,
    [string]$CallerSnapshot
  )
  $snapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'combat-caller-data-status.json') `
    -SnapshotPath (Join-Path $OutDir 'combat-caller-data-console.txt') `
    -Command 'D 3581:1820'
  $bytes = [byte[]](Get-DebuggerDataBytes $snapshot)
  if ($bytes.Length -lt 32) { throw "combat caller exposed only $($bytes.Length) data bytes" }
  $expectedPrefix = [byte[]](0xD6,0x49,0x26,0x89,0x85,0x82,0x05,0x9A,0x25,0x00)
  if (-not [Linq.Enumerable]::SequenceEqual([byte[]]$bytes[0..9], $expectedPrefix)) {
    throw 'runtime combat caller does not match retail GAME.OVR:0x2566 prefix'
  }
  $stubSegment = [uint16]($bytes[10] -bor ($bytes[11] -shl 8))
  $stubAddress = '{0:X4}:0025' -f $stubSegment
  Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'combat-stub-arm-status.json') `
    -SnapshotPath (Join-Path $OutDir 'combat-stub-arm-console.txt') `
    -Command "BP $stubAddress" | Out-Null
  Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'combat-stub-run-status.json') `
    -SnapshotPath (Join-Path $OutDir 'combat-stub-run-console.txt') -Command 'RUN' | Out-Null
  $stubHit = Wait-DebuggerAddress -ProcessId $ProcessId -HelperDll $HelperDll `
    -OutDir $OutDir -Label 'combat-stub'
  if ($stubHit.address -ne $stubAddress) {
    throw "expected runtime VROOMM stub $stubAddress, stopped at $($stubHit.address)"
  }
  $stubCodePattern = '(?m)^{0}:0*0025\s+CD3F' -f $stubAddress.Split(':')[0]
  if ($stubHit.snapshot -notmatch $stubCodePattern) {
    throw "runtime VROOMM stub $stubAddress does not begin INT 3F"
  }

  $resolvedSnapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'combat-stub-step-status.json') `
    -SnapshotPath (Join-Path $OutDir 'combat-stub-step-console.txt') -Key 'F11'
  $resolvedAddress = Get-DebuggerAddress $resolvedSnapshot
  if (-not $resolvedAddress) { throw 'F11 through combat VROOMM stub exposed no CS:EIP' }
  return [ordered]@{
    static_callsite = $CombatCaller
    callsite_prefix_hex = [Convert]::ToHexString([byte[]]$bytes[0..9]).ToLowerInvariant()
    relocated_stub_segment = ('{0:X4}' -f $stubSegment)
    runtime_stub_cs_ip = $stubAddress
    runtime_stub_bytes = 'CD3F'
    first_cs_ip_after_int3f_step = $resolvedAddress
  }
}

function Test-SeekHit {
  param([string]$Snapshot)
  if ($Snapshot -match '(?m)^\(Running\)\s*$') { return $false }
  $eaxMatch = [regex]::Match($Snapshot, '\bEAX=([0-9A-F]{8})\b')
  if (-not $eaxMatch.Success) { return $false }
  $eax = [Convert]::ToUInt32($eaxMatch.Groups[1].Value, 16)
  return (($eax -shr 8) -band 0xFF) -eq 0x42
}

function Get-DebuggerAddress {
  param([string]$Snapshot)
  $match = [regex]::Match($Snapshot, '\bCS=([0-9A-F]{4})\s+EIP=([0-9A-F]{8})\b')
  if (-not $match.Success) { return $null }
  return '{0}:{1}' -f $match.Groups[1].Value, $match.Groups[2].Value.Substring(4)
}

function Wait-DebuggerAddress {
  param(
    [int]$ProcessId,
    [string]$HelperDll,
    [string]$OutDir,
    [string]$Label,
    [int]$TimeoutSec = 10
  )
  $deadline = (Get-Date).AddSeconds($TimeoutSec)
  do {
    Start-Sleep -Milliseconds 100
    $snapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
      -StatusPath (Join-Path $OutDir "$Label-poll-status.json") `
      -SnapshotPath (Join-Path $OutDir "$Label-poll-console.txt") -SnapshotOnly
    if ($snapshot -notmatch '(?m)^\(Running\)\s*$') {
      $address = Get-DebuggerAddress $snapshot
      if ($address) {
        [IO.File]::WriteAllText(
          (Join-Path $OutDir "$Label-console.txt"),
          $snapshot,
          [Text.UTF8Encoding]::new($false)
        )
        return [ordered]@{ address = $address; snapshot = $snapshot }
      }
    }
  } while ((Get-Date) -lt $deadline)
  throw "timed out waiting for debugger stop: $Label"
}

function Get-DebuggerDataBytes {
  param([string]$Snapshot)
  $bytes = [Collections.Generic.List[byte]]::new()
  foreach ($line in ($Snapshot -split "`r?`n")) {
    $match = [regex]::Match(
      $line,
      '^[0-9A-F]{4}:[0-9A-F]{8}\s+((?:[0-9A-F]{2}\s+){15}[0-9A-F]{2})\s'
    )
    if (-not $match.Success) { continue }
    foreach ($hex in ($match.Groups[1].Value -split '\s+')) {
      if ($hex) { $bytes.Add([Convert]::ToByte($hex, 16)) }
    }
  }
  return ,$bytes.ToArray()
}

function Capture-EclCursor {
  param(
    [int]$ProcessId,
    [string]$HelperDll,
    [string]$OutDir,
    [string]$Phase,
    [string]$ParserSnapshot,
    [int]$Index
  )
  $parserIdentity = '(?ms)^30CF:00000000\s+55\s+.*\r?\n30CF:00000001\s+89E5\s+'
  if ($ParserSnapshot -notmatch $parserIdentity) {
    throw 'operand-parser breakpoint lacks retail 55 89 E5 prologue identity'
  }
  $dsMatch = [regex]::Match($ParserSnapshot, '\bDS=([0-9A-F]{4})\b')
  if (-not $dsMatch.Success) { throw 'operand-parser breakpoint lacks DS'
  }
  $ds = $dsMatch.Groups[1].Value
  $label = 'ecl-cursor-{0:D4}' -f $Index
  $snapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir "$label-status.json") `
    -SnapshotPath (Join-Path $OutDir "$label-console.txt") `
    -Command ('D {0}:{1:X4}' -f $ds, $EclCursorDgroupOffset)
  $bytes = [byte[]](Get-DebuggerDataBytes $snapshot)
  if ($bytes.Length -lt 2) { throw 'ECL cursor data view exposed fewer than two bytes' }
  $rawOffset = [uint16]($bytes[0] -bor ($bytes[1] -shl 8))
  return [ordered]@{
    index = $Index
    phase = $Phase
    parser_cs_ip = $OperandParser
    dgroup_segment = $ds
    dgroup_offset = $EclCursorDgroupOffset
    raw_member_offset = $rawOffset
    virtual_address = [uint16](($rawOffset - 2 - 0x6700) -band 0xFFFF)
  }
}

function Capture-EclHostState {
  param(
    [int]$ProcessId,
    [string]$HelperDll,
    [string]$OutDir,
    [string]$PausedSnapshot
  )
  $dsMatch = [regex]::Match($PausedSnapshot, '\bDS=([0-9A-F]{4})\b')
  if (-not $dsMatch.Success) { throw 'paused debugger snapshot lacks DS for ECL host state' }
  $ds = $dsMatch.Groups[1].Value
  $headerSnapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'ecl-host-header-status.json') `
    -SnapshotPath (Join-Path $OutDir 'ecl-host-header-console.txt') `
    -Command ('D {0}:{1:X4}' -f $ds, $EclHeaderDgroupOffset)
  $headerBytes = [byte[]](Get-DebuggerDataBytes $headerSnapshot)
  if ($headerBytes.Count -lt 10) { throw 'ECL host header dump returned fewer than ten bytes' }
  $entries = [ordered]@{}
  for ($index = 0; $index -lt $EclHeaderEntryNames.Count; $index++) {
    $low = [int]$headerBytes[$index * 2]
    $high = [int]$headerBytes[$index * 2 + 1]
    $entries[$EclHeaderEntryNames[$index]] = $low -bor ($high -shl 8)
  }
  $areaPointerSnapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'ecl-area-pointer-status.json') `
    -SnapshotPath (Join-Path $OutDir 'ecl-area-pointer-console.txt') `
    -Command ('D {0}:{1:X4}' -f $ds, $AreaPointerDgroupOffset)
  $areaPointerBytes = [byte[]](Get-DebuggerDataBytes $areaPointerSnapshot)
  if ($areaPointerBytes.Count -lt 4) { throw 'area-pointer dump returned fewer than four bytes' }
  $areaOffset = [int]$areaPointerBytes[0] -bor ([int]$areaPointerBytes[1] -shl 8)
  $areaSegment = [int]$areaPointerBytes[2] -bor ([int]$areaPointerBytes[3] -shl 8)
  $memberAddress = ($areaOffset + $AreaEclMemberFieldOffset) -band 0xFFFF
  $memberSnapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'ecl-area-member-status.json') `
    -SnapshotPath (Join-Path $OutDir 'ecl-area-member-console.txt') `
    -Command ('D {0:X4}:{1:X4}' -f $areaSegment, $memberAddress)
  $memberBytes = [byte[]](Get-DebuggerDataBytes $memberSnapshot)
  if ($memberBytes.Count -lt 1) { throw 'area ECL member dump returned no bytes' }
  $archiveSetSnapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'ecl-archive-set-status.json') `
    -SnapshotPath (Join-Path $OutDir 'ecl-archive-set-console.txt') `
    -Command ('D {0}:{1:X4}' -f $ds, $ArchiveSetDgroupOffset)
  $archiveSetBytes = [byte[]](Get-DebuggerDataBytes $archiveSetSnapshot)
  if ($archiveSetBytes.Count -lt 1) { throw 'ECL archive-set dump returned no bytes' }
  $cellSnapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'ecl-map-cell-status.json') `
    -SnapshotPath (Join-Path $OutDir 'ecl-map-cell-console.txt') `
    -Command ('D {0}:{1:X4}' -f $ds, $MapCellDgroupOffset)
  $cellBytes = [byte[]](Get-DebuggerDataBytes $cellSnapshot)
  if ($cellBytes.Count -lt 1) { throw 'map-cell dump returned no bytes' }
  return [ordered]@{
    dgroup_segment = $ds
    header_table_offset = $EclHeaderDgroupOffset
    header_entries = $entries
    area_pointer = ('{0:X4}:{1:X4}' -f $areaSegment, $areaOffset)
    area_ecl_member_field_offset = $AreaEclMemberFieldOffset
    area_ecl_member_id = [int]$memberBytes[0]
    archive_set_dgroup_offset = $ArchiveSetDgroupOffset
    archive_set = [int]$archiveSetBytes[0]
    map_cell_virtual_address = $MapCellVirtualAddress
    map_cell_dgroup_offset = $MapCellDgroupOffset
    map_cell_byte = [int]$cellBytes[0]
  }
}

function Invoke-CombatEntryProbe {
  param(
    [int]$ProcessId,
    [string]$HelperDll,
    [string]$OutDir,
    [string]$SeekSnapshot,
    [string]$OverlayPath
  )
  $destinationMatch = [regex]::Match($SeekSnapshot, 'es:\[0010\]=([0-9A-F]{4})')
  $loaderMatch = [regex]::Match($SeekSnapshot, '\bCS=([0-9A-F]{4})\s+EIP=([0-9A-F]{8})\b')
  if (-not $destinationMatch.Success -or -not $loaderMatch.Success) {
    throw 'descriptor-8 seek lacks destination segment or loader CS:EIP'
  }
  $destination = $destinationMatch.Groups[1].Value
  $loaderCs = $loaderMatch.Groups[1].Value
  $seekEip = [Convert]::ToUInt32($loaderMatch.Groups[2].Value, 16)
  $postRead = '{0}:{1:X4}' -f $loaderCs, ($seekEip + 0x12)
  $encodedEntry = "$destination`:087A"
  $prologueEntry = "$destination`:0880"
  $secondEntry = "$destination`:127A"

  $overlay = [IO.File]::ReadAllBytes($OverlayPath)
  $descriptor = $overlay[$CombatSetupSeekOffset..($CombatSetupSeekOffset + $CombatSetupCodeSize - 1)]
  $descriptorHash = [Convert]::ToHexString(
    [Security.Cryptography.SHA256]::HashData([byte[]]$descriptor)
  ).ToLowerInvariant()
  if ($descriptorHash -ne $ExpectedCombatSetupSha256) {
    throw "descriptor-8 source hash mismatch: $descriptorHash"
  }

  foreach ($address in @($postRead, $encodedEntry, $prologueEntry, $secondEntry)) {
    Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
      -StatusPath (Join-Path $OutDir ('combat-arm-{0}.json' -f ($address -replace ':','-'))) `
      -SnapshotPath (Join-Path $OutDir ('combat-arm-{0}.txt' -f ($address -replace ':','-'))) `
      -Command "BP $address" | Out-Null
  }
  Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'combat-post-read-run.json') `
    -SnapshotPath (Join-Path $OutDir 'combat-post-read-run.txt') -Command 'RUN' | Out-Null
  $postReadHit = Wait-DebuggerAddress -ProcessId $ProcessId -HelperDll $HelperDll `
    -OutDir $OutDir -Label 'combat-post-read'
  if ($postReadHit.address -ne $postRead) {
    throw "expected descriptor post-read at $postRead, stopped at $($postReadHit.address)"
  }

  $residentSnapshots = @()
  foreach ($offset in @(0x0000, 0x0870)) {
    $label = 'combat-resident-{0:X4}' -f $offset
    $snapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
      -StatusPath (Join-Path $OutDir "$label-status.json") `
      -SnapshotPath (Join-Path $OutDir "$label-console.txt") `
      -Command ('D {0}:{1:X4}' -f $destination, $offset)
    $resident = [byte[]](Get-DebuggerDataBytes $snapshot)
    if ($resident.Length -lt 64) { throw "$label exposed only $($resident.Length) data bytes" }
    $expected = [byte[]]$descriptor[$offset..($offset + $resident.Length - 1)]
    $matches = [Linq.Enumerable]::SequenceEqual($resident, $expected)
    if (-not $matches) { throw "$label does not match the retail descriptor before fixups" }
    $residentSnapshots += [ordered]@{
      offset = $offset
      byte_count = $resident.Length
      sha256 = [Convert]::ToHexString(
        [Security.Cryptography.SHA256]::HashData($resident)
      ).ToLowerInvariant()
      exact_retail_match = $matches
    }
  }

  Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
    -StatusPath (Join-Path $OutDir 'combat-entry-run.json') `
    -SnapshotPath (Join-Path $OutDir 'combat-entry-run.txt') -Command 'RUN' | Out-Null
  $entryHit = $null
  $intermediateStops = @()
  for ($stopIndex = 0; $stopIndex -lt 64; $stopIndex++) {
    $hit = Wait-DebuggerAddress -ProcessId $ProcessId -HelperDll $HelperDll `
      -OutDir $OutDir -Label ('combat-entry-{0:D2}' -f $stopIndex)
    if ($hit.address -in @($encodedEntry, $prologueEntry, $secondEntry)) {
      $entryHit = $hit
      break
    }
    $intermediateStops += $hit.address
    Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
      -StatusPath (Join-Path $OutDir ('combat-entry-continue-{0:D2}.json' -f $stopIndex)) `
      -SnapshotPath (Join-Path $OutDir ('combat-entry-continue-{0:D2}.txt' -f $stopIndex)) `
      -Command 'RUN' | Out-Null
  }
  if ($null -eq $entryHit) {
    throw "descriptor-8 entry not reached after 64 debugger stops"
  }

  return [ordered]@{
    descriptor_index = 8
    seek_offset = $CombatSetupSeekOffset
    code_size = $CombatSetupCodeSize
    source_sha256 = $descriptorHash
    destination_segment = $destination
    loader_seek_cs_ip = Get-DebuggerAddress $SeekSnapshot
    loader_post_read_cs_ip = $postReadHit.address
    encoded_public_entry = $encodedEntry
    byte_validated_prologue_entry = $prologueEntry
    second_public_entry = $secondEntry
    executed_entry_cs_ip = $entryHit.address
    intermediate_stop_count = $intermediateStops.Count
    intermediate_stops = $intermediateStops
    resident_checks = $residentSnapshots
    claim = 'byte-identical post-read descriptor image plus execution breakpoint'
  }
}

function Collect-DebuggerSeeks {
  param(
    [hashtable]$State,
    [string]$Phase,
    [int]$ProcessId,
    [string]$HelperDll,
    [string]$OutDir,
    [int]$MaxTotalSeeks,
    [int]$FirstTimeoutSec,
    [int]$NextTimeoutMs,
    [switch]$RequireHit
  )
  $phaseHits = 0
  $lastFingerprint = ''
  $repeatedFingerprintCount = 0
  $deadline = (Get-Date).AddSeconds($FirstTimeoutSec)
  while ($State.seek_count -lt $MaxTotalSeeks) {
    $hit = $false
    $callerHit = $false
    do {
      Start-Sleep -Milliseconds 250
      $snapshot = Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
        -StatusPath (Join-Path $OutDir 'poll_status.json') `
        -SnapshotPath (Join-Path $OutDir 'poll_console.txt') -SnapshotOnly
      $hit = Test-SeekHit $snapshot
      $callerHit = $StopAtCombatEntry -and (Get-DebuggerAddress $snapshot) -eq $CombatCaller
      $parserHit = $TraceEclCursor -and (Get-DebuggerAddress $snapshot) -eq $OperandParser
      if ($parserHit) {
        $State.ecl_cursor_records += Capture-EclCursor -ProcessId $ProcessId `
          -HelperDll $HelperDll -OutDir $OutDir -Phase $Phase -ParserSnapshot $snapshot `
          -Index $State.ecl_cursor_records.Count
        $State.ecl_cursor_records | ConvertTo-Json -Depth 4 | Set-Content `
          -LiteralPath (Join-Path $OutDir 'ecl-cursor-live.json') -Encoding utf8
        if ($State.ecl_cursor_records.Count -ge $MaxEclCursorHits) {
          $State.cursor_limit = $true
          break
        }
        Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
          -StatusPath (Join-Path $OutDir 'ecl-cursor-continue-status.json') `
          -SnapshotPath (Join-Path $OutDir 'ecl-cursor-continue-console.txt') `
          -Command 'RUN' | Out-Null
        $deadline = (Get-Date).AddMilliseconds($NextTimeoutMs)
      }
    } while (-not $hit -and -not $callerHit -and -not $State.cursor_limit -and (Get-Date) -lt $deadline)

    if ($State.cursor_limit) { break }

    if ($callerHit) {
      [IO.File]::WriteAllText(
        (Join-Path $OutDir 'combat-caller-console.txt'),
        $snapshot,
        [Text.UTF8Encoding]::new($false)
      )
      $State.caller_probe = Invoke-CombatCallerProbe -ProcessId $ProcessId -HelperDll $HelperDll `
        -OutDir $OutDir -CallerSnapshot $snapshot
      $State.stop_requested = $true
      break
    }

    if (-not $hit) {
      if ($RequireHit -and $phaseHits -eq 0) {
        throw "phase $Phase produced no INT 21/AH=42 seek hit before timeout"
      }
      break
    }

    $fingerprint = ([regex]::Matches(
      $snapshot,
      '\b(?:EAX|EBX|ECX|EDX|ES|CS|EIP)=([0-9A-F]{4,8})\b'
    ) | ForEach-Object Value) -join ';'
    if ($fingerprint -eq $lastFingerprint) {
      $repeatedFingerprintCount++
      if ($repeatedFingerprintCount -ge 8) {
        throw "debugger RUN did not advance after eight identical seek snapshots"
      }
    } else {
      $lastFingerprint = $fingerprint
      $repeatedFingerprintCount = 0
    }

    $snapshotPath = Join-Path $OutDir ('debugger_console_{0}.txt' -f $State.seek_count)
    [IO.File]::WriteAllText($snapshotPath, $snapshot, [Text.UTF8Encoding]::new($false))
    $ebxMatch = [regex]::Match($snapshot, '\bEBX=([0-9A-F]{8})\b')
    $seekOffset = $null
    if ($ebxMatch.Success -and [Convert]::ToUInt32($ebxMatch.Groups[1].Value, 16) -eq 5) {
      $State.game_ovr_seek_count++
      $ecxMatch = [regex]::Match($snapshot, '\bECX=([0-9A-F]{8})\b')
      $edxMatch = [regex]::Match($snapshot, '\bEDX=([0-9A-F]{8})\b')
      if ($ecxMatch.Success -and $edxMatch.Success) {
        $seekOffset = (
          ([Convert]::ToUInt32($ecxMatch.Groups[1].Value, 16) -band 0xFFFF) -shl 16
        ) -bor ([Convert]::ToUInt32($edxMatch.Groups[1].Value, 16) -band 0xFFFF)
        $State.game_ovr_offsets += [uint32]$seekOffset
      }
    }
    $State.seek_count++
    $phaseHits++
    if ($StopAtCombatEntry -and $seekOffset -eq $CombatSetupSeekOffset) {
      $State.combat_probe = Invoke-CombatEntryProbe -ProcessId $ProcessId -HelperDll $HelperDll `
        -OutDir $OutDir -SeekSnapshot $snapshot -OverlayPath $State.overlay_path
      $State.stop_requested = $true
      break
    }
    Invoke-DebuggerInput -ProcessId $ProcessId -HelperDll $HelperDll `
      -StatusPath (Join-Path $OutDir 'continue_status.json') `
      -SnapshotPath (Join-Path $OutDir 'continue_console.txt') -Command 'RUN' | Out-Null
    $deadline = (Get-Date).AddMilliseconds($NextTimeoutMs)
  }
  $State.phases[$Phase] = $phaseHits
  $State.phase_ranges += [ordered]@{
    phase = $Phase
    start_snapshot = $State.seek_count - $phaseHits
    snapshot_count = $phaseHits
  }
  return $phaseHits
}

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$dbx = (Resolve-Path (Join-Path $repo $DbxExe)).Path
$stage = (Resolve-Path (Join-Path $repo $StageDir)).Path
$out = Join-Path $repo $OutDir
if (Test-Path -LiteralPath $out) { throw "output directory already exists: $out" }
$pool = Join-Path $stage 'POOLRAD'
$save = Join-Path $pool 'SAVGAMG.DAT'
if (-not (Test-Path -LiteralPath $save -PathType Leaf)) { throw "missing route save: $save" }
$saveHash = (Get-FileHash -LiteralPath $save -Algorithm SHA256).Hash.ToLowerInvariant()
if ($saveHash -ne $ExpectedRouteSaveSha256) { throw "unexpected G save hash: $saveHash" }

$saveText = [Text.Encoding]::ASCII.GetString([IO.File]::ReadAllBytes($save))
$references = @([regex]::Matches($saveText, 'CHRDAT([A-J])[1-6]') | ForEach-Object Value | Sort-Object -Unique)
if ($references.Count -ne 6) { throw "expected six embedded CHRDAT references, found $($references.Count)" }
$sidecars = @(Get-ChildItem -LiteralPath $pool -File | Where-Object {
  $name = $_.BaseName
  $references -contains $name -and $_.Extension -in @('.SAV', '.ITM', '.SPC')
})
if ($sidecars.Count -ne 16) { throw "expected 16 referenced route sidecars, found $($sidecars.Count)" }

$probe = Join-Path $repo 'tools\dosbox_x_debugbox_probe.ps1'
$helperProject = Join-Path $repo 'tools\dosbox_debugger_input\DosboxDebuggerInput.csproj'
$helperDll = Join-Path $repo 'tools\dosbox_debugger_input\bin\Release\net9.0-windows\DosboxDebuggerInput.dll'
& dotnet build $helperProject --configuration Release | Out-Null
if ($LASTEXITCODE -ne 0) { throw "debugger helper build failed: $LASTEXITCODE" }

$process = $null
try {
  & $probe -DbxExe $dbx -GameDir $stage -DosWorkingDir 'POOLRAD' -Exe 'START.EXE' `
    -OutDir $out -Cycles 'fixed 25000' -DebuggerAction @('RUN') -NoActionScreenshots
  if ($LASTEXITCODE -ne 0) { throw "DEBUGBOX probe failed: $LASTEXITCODE" }

  $metadata = Get-Content -LiteralPath (Join-Path $out 'probe-process.json') -Raw | ConvertFrom-Json
  $process = Get-Process -Id ([int]$metadata.process_id)
  $renderRecord = @($metadata.windows | Where-Object role -eq 'render')
  $debugRecord = @($metadata.windows | Where-Object role -eq 'debugger-console')
  if ($renderRecord.Count -ne 1 -or $debugRecord.Count -ne 1) {
    throw "expected one render and one debugger window"
  }
  $renderHwnd = [IntPtr]([int64]$renderRecord[0].hwnd)
  $debugHwnd = [IntPtr]([int64]$debugRecord[0].hwnd)

  . (Join-Path $repo 'tools\dosbot\lib.ps1')
  Start-Sleep -Seconds 2
  Send-DosKeys -Hwnd $renderHwnd -Keys 'L'
  Start-Sleep -Seconds 2
  Send-DosKeys -Hwnd $renderHwnd -Keys '{G}{ENTER}'
  Start-Sleep -Seconds 5
  Capture-DosboxPrintWindow -Hwnd $renderHwnd -OutPng (Join-Path $out 'route_00_neighbor.png') | Out-Null

  if ($PreTraceKeys.Length -gt 0) {
    Send-DosKeys -Hwnd $renderHwnd -Keys $PreTraceKeys
    Start-Sleep -Seconds 1
  }
  $tracePrefixTokens = @([regex]::Matches($TracePrefixKeys, '\{[^}]+\}|.') | ForEach-Object Value)
  for ($prefixIndex = 0; $prefixIndex -lt $tracePrefixTokens.Count; $prefixIndex++) {
    Send-DosKeys -Hwnd $renderHwnd -Keys $tracePrefixTokens[$prefixIndex]
    Start-Sleep -Milliseconds 750
    Capture-DosboxPrintWindow -Hwnd $renderHwnd `
      -OutPng (Join-Path $out ('route_prefix_{0:D2}.png' -f $prefixIndex)) | Out-Null
  }
  Click-DosboxMenuItem -Hwnd $renderHwnd -MenuX 342 -MenuY 39 -ItemX 342 -ItemY 62
  Start-Sleep -Seconds 1

  $paused = Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
    -StatusPath (Join-Path $out 'pause_status.json') `
    -SnapshotPath (Join-Path $out 'pause_console.txt') -SnapshotOnly
  if ($paused -match '\(Running\)\s*$') { throw "Debug menu did not pause emulation" }
  $initialEclHostState = $null
  if ($TraceEclCursor) {
    $initialEclHostState = Capture-EclHostState -ProcessId $process.Id -HelperDll $helperDll `
      -OutDir $out -PausedSnapshot $paused
    $initialEclHostState | ConvertTo-Json -Depth 5 | Set-Content `
      -LiteralPath (Join-Path $out 'ecl-initial-host-state.json') -Encoding utf8
  }

  $armed = Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
    -StatusPath (Join-Path $out 'arm_status.json') `
    -SnapshotPath (Join-Path $out 'arm_console.txt') -Command 'BPINT 21 42'
  if ($armed -notmatch 'DEBUG: Set interrupt breakpoint at INT 21 AH=42') {
    throw "INT 21/AH=42 breakpoint was not acknowledged"
  }
  if ($StopAtCombatEntry) {
    Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
      -StatusPath (Join-Path $out 'combat-caller-arm-status.json') `
      -SnapshotPath (Join-Path $out 'combat-caller-arm-console.txt') `
      -Command "BP $CombatCaller" | Out-Null
  }
  Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
    -StatusPath (Join-Path $out 'run_status.json') `
    -SnapshotPath (Join-Path $out 'run_console.txt') -Command 'RUN' | Out-Null

  $traceState = @{
    seek_count = 0
    game_ovr_seek_count = 0
    game_ovr_offsets = @()
    phases = @{}
    phase_ranges = @()
    overlay_path = (Join-Path $pool 'GAME.OVR')
    combat_probe = $null
    caller_probe = $null
    ecl_cursor_records = @()
    cursor_limit = $false
    stop_requested = $false
  }
  if ($TraceEclCursor) {
    # Arm before the first forward step. A selected encounter may open a modal menu immediately,
    # so tracing a later leave/re-entry can miss the host's actual search dispatch.
    Click-DosboxMenuItem -Hwnd $renderHwnd -MenuX 342 -MenuY 39 -ItemX 342 -ItemY 62
    Start-Sleep -Seconds 1
    $cursorPause = Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
      -StatusPath (Join-Path $out 'ecl-parser-pause-status.json') `
      -SnapshotPath (Join-Path $out 'ecl-parser-pause-console.txt') -SnapshotOnly
    if ($cursorPause -match '(?m)^\(Running\)\s*$') { throw 'failed to pause before ECL cursor trace' }
    Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
      -StatusPath (Join-Path $out 'ecl-parser-arm-status.json') `
      -SnapshotPath (Join-Path $out 'ecl-parser-arm-console.txt') `
      -Command "BP $OperandParser" | Out-Null
    Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
      -StatusPath (Join-Path $out 'ecl-parser-run-status.json') `
      -SnapshotPath (Join-Path $out 'ecl-parser-run-console.txt') -Command 'RUN' | Out-Null

    $traceKeys = @([regex]::Matches($TraceEntryKeys, '\{[^}]+\}|.') | ForEach-Object Value)
    if ($traceKeys.Count -eq 0) { throw 'TraceEntryKeys contains no key tokens' }
    for ($keyIndex = 0; $keyIndex -lt $traceKeys.Count; $keyIndex++) {
      Send-DosKeys -Hwnd $renderHwnd -Keys $traceKeys[$keyIndex]
      Collect-DebuggerSeeks -State $traceState -Phase ('cursor-step-{0:D2}' -f $keyIndex) `
        -ProcessId $process.Id -HelperDll $helperDll -OutDir $out -MaxTotalSeeks $MaxSeeks `
        -FirstTimeoutSec 3 -NextTimeoutMs $NextSeekTimeoutMs | Out-Null
      Capture-DosboxPrintWindow -Hwnd $renderHwnd `
        -OutPng (Join-Path $out ('route_key_{0:D2}.png' -f $keyIndex)) | Out-Null
      if ($traceState.cursor_limit) { break }
    }
    if ($traceState.ecl_cursor_records.Count -eq 0) {
      throw 'no ECL parser hits; an RNG encounter or modal screen blocked the traced movement'
    }
    Start-Sleep -Seconds 1
    Capture-DosboxPrintWindow -Hwnd $renderHwnd `
      -OutPng (Join-Path $out 'ecl_cursor_target.png') | Out-Null
    $afterEntryPause = Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
      -StatusPath (Join-Path $out 'ecl-after-entry-status.json') `
      -SnapshotPath (Join-Path $out 'ecl-after-entry-console.txt') -SnapshotOnly
    if ($afterEntryPause -match '(?m)^\(Running\)\s*$') {
      Click-DosboxMenuItem -Hwnd $renderHwnd -MenuX 342 -MenuY 39 -ItemX 342 -ItemY 62
      Start-Sleep -Seconds 1
      $afterEntryPause = Invoke-DebuggerInput -ProcessId $process.Id -HelperDll $helperDll `
        -StatusPath (Join-Path $out 'ecl-after-entry-paused-status.json') `
        -SnapshotPath (Join-Path $out 'ecl-after-entry-paused-console.txt') -SnapshotOnly
    }
    $afterDs = [regex]::Match($afterEntryPause, '\bDS=([0-9A-F]{4})\b')
    $afterEntryHostState = $null
    if ($afterDs.Success -and $afterDs.Groups[1].Value -eq $initialEclHostState.dgroup_segment) {
      $afterEntryHostState = Capture-EclHostState -ProcessId $process.Id -HelperDll $helperDll `
        -OutDir $out -PausedSnapshot $afterEntryPause
    }
    $searchHits = @($traceState.ecl_cursor_records | Where-Object {
      $_.virtual_address -ge $SearchCursorFloor -and $_.virtual_address -lt $SearchCursorCeiling
    })
    [ordered]@{
      schema_version = 1
      title = 'Pool of Radiance'
      route = $TraceRouteLabel
      save_sha256 = $saveHash
      sidecar_count = $sidecars.Count
      pre_trace_keys = $PreTraceKeys
      trace_prefix_keys = $tracePrefixTokens
      trace_entry_keys = $traceKeys
      initial_host_state = $initialEclHostState
      after_entry_host_state = $afterEntryHostState
      ecl_cursor_records = $traceState.ecl_cursor_records
      target_search_location = $TargetSearchLocation
      parser_first_cursor_for_search_location = $SearchCursorFloor
      reached_search_location_range = $searchHits.Count -gt 0
      target_combat = $TargetCombatLocation
      claim_boundary = 'proves the ECL cursor range reached on direct entry; COMBAT has no operands and needs its own execution breakpoint'
    } | ConvertTo-Json -Depth 5 | Set-Content `
      -LiteralPath (Join-Path $out 'ecl-cursor-trace.json') -Encoding utf8
    Write-Host "[pool-ecl-cursor] hits=$($traceState.ecl_cursor_records.Count) search=$($searchHits.Count -gt 0) out=$out"
    return
  }

  Send-DosKeys -Hwnd $renderHwnd -Keys '{UP}'
  Collect-DebuggerSeeks -State $traceState -Phase 'entry' -ProcessId $process.Id `
    -HelperDll $helperDll -OutDir $out -MaxTotalSeeks $MaxSeeks `
    -FirstTimeoutSec $FirstSeekTimeoutSec -NextTimeoutMs $NextSeekTimeoutMs -RequireHit | Out-Null
  Start-Sleep -Seconds 2
  Capture-DosboxPrintWindow -Hwnd $renderHwnd -OutPng (Join-Path $out 'route_01_target.png') | Out-Null

  $lookHits = 0
  for ($lookAttempt = 1; $lookAttempt -le $LookAttempts -and $lookHits -eq 0; $lookAttempt++) {
    Send-DosKeys -Hwnd $renderHwnd -Keys 'L'
    $lookHits = Collect-DebuggerSeeks -State $traceState -Phase "look-$lookAttempt" `
      -ProcessId $process.Id -HelperDll $helperDll -OutDir $out -MaxTotalSeeks $MaxSeeks `
      -FirstTimeoutSec 3 -NextTimeoutMs $NextSeekTimeoutMs
    if ($lookHits -eq 0 -and $lookAttempt -lt $LookAttempts) {
      Send-DosKeys -Hwnd $renderHwnd -Keys '{LEFT}{LEFT}{UP}'
      Collect-DebuggerSeeks -State $traceState -Phase "leave-$lookAttempt" `
        -ProcessId $process.Id -HelperDll $helperDll -OutDir $out -MaxTotalSeeks $MaxSeeks `
        -FirstTimeoutSec 2 -NextTimeoutMs $NextSeekTimeoutMs | Out-Null
      if ($TraceEclCursor) {
        Capture-DosboxPrintWindow -Hwnd $renderHwnd `
          -OutPng (Join-Path $out ('route_retry_{0:D2}_leave.png' -f $lookAttempt)) | Out-Null
      }
      Send-DosKeys -Hwnd $renderHwnd -Keys '{LEFT}{LEFT}{UP}'
      Collect-DebuggerSeeks -State $traceState -Phase "reenter-$lookAttempt" `
        -ProcessId $process.Id -HelperDll $helperDll -OutDir $out -MaxTotalSeeks $MaxSeeks `
        -FirstTimeoutSec 2 -NextTimeoutMs $NextSeekTimeoutMs | Out-Null
      if ($TraceEclCursor) {
        Capture-DosboxPrintWindow -Hwnd $renderHwnd `
          -OutPng (Join-Path $out ('route_retry_{0:D2}_reenter.png' -f $lookAttempt)) | Out-Null
      }
    }
  }
  if ($lookHits -eq 0) { throw "LOOK did not produce the route encounter after $LookAttempts attempts" }
  Start-Sleep -Seconds 2
  Capture-DosboxPrintWindow -Hwnd $renderHwnd -OutPng (Join-Path $out 'route_02_encounter_text.png') | Out-Null

  Send-DosKeys -Hwnd $renderHwnd -Keys '{ENTER}'
  Collect-DebuggerSeeks -State $traceState -Phase 'encounter-continue' -ProcessId $process.Id `
    -HelperDll $helperDll -OutDir $out -MaxTotalSeeks $MaxSeeks `
    -FirstTimeoutSec 2 -NextTimeoutMs $NextSeekTimeoutMs | Out-Null
  if ($traceState.stop_requested) {
    [ordered]@{
      schema_version = 1
      title = 'Pool of Radiance'
      route = 'ECL1#18 at (14,8), SEARCH, forced surprise combat'
      save_sha256 = $saveHash
      sidecar_count = $sidecars.Count
      seek_count = $traceState.seek_count
      phase_seek_counts = $traceState.phases
      combat_probe = $traceState.combat_probe
      caller_probe = $traceState.caller_probe
      claim_boundary = 'proves a bounded combat call/overlay boundary; not combat outcome or ECL resume'
    } | ConvertTo-Json -Depth 6 | Set-Content `
      -LiteralPath (Join-Path $out 'combat-entry-trace.json') -Encoding utf8
    Write-Host "[pool-combat-entry] reached=$($traceState.combat_probe.executed_entry_cs_ip) out=$out"
    return
  }
  Start-Sleep -Seconds 2
  Capture-DosboxPrintWindow -Hwnd $renderHwnd -OutPng (Join-Path $out 'route_03_after_continue.png') | Out-Null

  $combatWasForced = $traceState.game_ovr_offsets -contains $CombatSetupSeekOffset
  if (-not $combatWasForced) {
    Send-DosKeys -Hwnd $renderHwnd -Keys 'C'
    Collect-DebuggerSeeks -State $traceState -Phase 'combat-choice' -ProcessId $process.Id `
      -HelperDll $helperDll -OutDir $out -MaxTotalSeeks $MaxSeeks `
      -FirstTimeoutSec $FirstSeekTimeoutSec -NextTimeoutMs $NextSeekTimeoutMs -RequireHit | Out-Null
  } else {
    $traceState.phases['combat-choice'] = 0
  }
  if ($traceState.game_ovr_offsets -notcontains $CombatSetupSeekOffset) {
    throw 'combat setup descriptor 8 was not loaded after encounter continuation/choice'
  }
  Start-Sleep -Seconds 2
  Capture-DosboxPrintWindow -Hwnd $renderHwnd -OutPng (Join-Path $out 'route_04_combat.png') | Out-Null
  [ordered]@{
    schema_version = 1
    title = 'Pool of Radiance'
    route = 'ECL1#18 at (14,8), SEARCH, first target entry'
    save_sha256 = $saveHash
    embedded_sidecar_references = $references
    sidecar_count = $sidecars.Count
    seek_count = $traceState.seek_count
    game_ovr_seek_count = $traceState.game_ovr_seek_count
    game_ovr_seek_offsets = $traceState.game_ovr_offsets
    phase_seek_counts = $traceState.phases
    phase_ranges = $traceState.phase_ranges
    combat_was_forced = $combatWasForced
    ecl_cursor_records = $traceState.ecl_cursor_records
    process_metadata = 'probe-process.json'
  } | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath (Join-Path $out 'route-trace.json') -Encoding utf8
  Write-Host "[pool-route-trace] seeks=$($traceState.seek_count) game_ovr_seeks=$($traceState.game_ovr_seek_count) out=$out"
} finally {
  if (-not $KeepRunning -and $process -and -not $process.HasExited) {
    Stop-Process -Id $process.Id
    Wait-Process -Id $process.Id -ErrorAction SilentlyContinue
  }
}
